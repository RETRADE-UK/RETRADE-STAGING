async function downloadBytes(download,page){
  const failure=await download.failure();
  if(!failure)return fs.readFileSync(await download.path());
  // Some managed Windows hosts block the browser's download directory. This
  // explicit local QA mode still clicks the real download and checks its exact
  // generated Blob. CI leaves the switch unset and requires a successful file.
  assert(process.env.RETRADE_CAPTURE_BLOBS==='1','Browser download failed: '+failure);
  const bytes=await page.evaluate(async()=>window.__periodLastBlob?Array.from(new Uint8Array(await window.__periodLastBlob.arrayBuffer())):null);
  assert(bytes&&bytes.length,'No generated download Blob was captured');
  console.log('LOCAL QA: browser download '+failure+'; verified generated bytes for '+download.suggestedFilename());
  return Buffer.from(bytes);
}

